import type { UpdateLoadData } from '../core/load.repository';
import {
  DOCUMENT_COLUMNS,
  ExtraDocument,
  LOADSMART_REVIEWED_TYPES,
  LoadDocumentReviewStatus,
  LoadDocumentType,
  POD_DOCUMENT_TYPES,
  SET_DOCUMENT_TYPES,
} from './load-document.types';

/** Pure rules of the documents register — no DB/IO, unit-tested in document-rules.test.ts. */

export interface CurrentDocument {
  id: string;
  docType: LoadDocumentType;
  fileKey: string;
}

export interface NewDocument {
  docType: LoadDocumentType;
  fileKey: string;
  version: number;
  supersedesId: string | null;
}

export interface DocumentPlan {
  /** Current versions this write replaces or removes. */
  supersede: string[];
  add: NewDocument[];
}

/** What a write of `fields` (plus files outside the load's columns) does to the register: a new
 *  file supersedes the current version and becomes the next one; the same file again changes
 *  nothing; clearing a column supersedes without a replacement. Loading photos are a set — each
 *  photo added or dropped on its own. */
export function planDocumentChanges(
  current: CurrentDocument[],
  maxVersions: ReadonlyMap<LoadDocumentType, number>,
  fields: UpdateLoadData,
  extras: ExtraDocument[] = [],
): DocumentPlan {
  const plan: DocumentPlan = { supersede: [], add: [] };
  const next = new Map(maxVersions);
  const nextVersion = (docType: LoadDocumentType) => {
    const version = (next.get(docType) ?? 0) + 1;
    next.set(docType, version);
    return version;
  };

  const single = (docType: LoadDocumentType, fileKey: string | null) => {
    const existing = current.find((doc) => doc.docType === docType);
    if (existing?.fileKey === fileKey) return;
    if (existing) plan.supersede.push(existing.id);
    if (fileKey) {
      plan.add.push({
        docType,
        fileKey,
        version: nextVersion(docType),
        supersedesId: existing?.id ?? null,
      });
    }
  };

  for (const [docType, spec] of Object.entries(DOCUMENT_COLUMNS) as [
    LoadDocumentType,
    NonNullable<(typeof DOCUMENT_COLUMNS)[LoadDocumentType]>,
  ][]) {
    if (!(spec.column in fields) || fields[spec.column] === undefined) continue;
    const value = fields[spec.column] as string | string[] | null;
    if (!spec.multiple) {
      single(docType, value as string | null);
      continue;
    }
    const keys = [...new Set((value as string[] | null) ?? [])];
    const existing = current.filter((doc) => doc.docType === docType);
    for (const doc of existing) {
      if (!keys.includes(doc.fileKey)) plan.supersede.push(doc.id);
    }
    for (const fileKey of keys) {
      if (existing.some((doc) => doc.fileKey === fileKey)) continue;
      plan.add.push({ docType, fileKey, version: nextVersion(docType), supersedesId: null });
    }
  }
  for (const extra of extras) {
    if (!SET_DOCUMENT_TYPES.includes(extra.docType)) {
      single(extra.docType, extra.fileKey);
      continue;
    }
    // A set: add the file unless it is already there.
    const already = current.some(
      (doc) => doc.docType === extra.docType && doc.fileKey === extra.fileKey,
    );
    if (!already) {
      plan.add.push({
        docType: extra.docType,
        fileKey: extra.fileKey,
        version: nextVersion(extra.docType),
        supersedesId: null,
      });
    }
  }
  return plan;
}

/** Who has to check a new file: the POD's go with the POD decision; a Loadsmart load's papers
 *  wait for Loadsmart; the e-LR is generated by the system; anything else the shipper put on
 *  their own load needs nobody. */
export function initialReviewStatus(
  docType: LoadDocumentType,
  loadsmartLoad: boolean,
): LoadDocumentReviewStatus {
  if (POD_DOCUMENT_TYPES.includes(docType)) return 'pending';
  if (loadsmartLoad && LOADSMART_REVIEWED_TYPES.includes(docType)) return 'pending';
  return 'not_required';
}

/** Why `reviewer` can't decide this document, or null. */
export function reviewBlocker(
  doc: { docType: LoadDocumentType; supersededAt: Date | null; reviewStatus: string },
  loadsmartLoad: boolean,
  reviewer: 'shipper' | 'ls_team',
): string | null {
  if (doc.supersededAt) return 'A newer version of this document replaced it';
  if (POD_DOCUMENT_TYPES.includes(doc.docType)) {
    return 'POD documents are decided with the POD';
  }
  if (loadsmartLoad !== (reviewer === 'ls_team')) {
    return loadsmartLoad
      ? "On a Loadsmart load, Loadsmart's Tracking team reviews the documents"
      : 'The shipper reviews the documents on this load';
  }
  if (doc.reviewStatus === 'rejected') return 'Rejected — waiting for a new upload';
  return null;
}
