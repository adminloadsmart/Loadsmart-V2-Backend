const normalizeStateKey = (value: string) => value.toLowerCase().replace(/[^a-z]/g, '');

const STATE_BY_KEY: Record<string, IndianState> = {
  ...Object.fromEntries(INDIAN_STATES.map((state) => [normalizeStateKey(state), state])),
  ...STATE_ALIASES,
};

/** Canonical state for a typed value (any case, punctuation or common short form), else null. */
export function resolveIndianState(value: string): IndianState | null {
  return STATE_BY_KEY[normalizeStateKey(value)] ?? null;
}
